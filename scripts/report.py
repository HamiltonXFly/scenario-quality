from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from matplotlib.patches import Rectangle

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from sq import metrics  # noqa: E402

INK, MUTED, GRID = "#0b0b0b", "#52514e", "#e4e3df"
CLASS_STYLE = {   # label, fill, text colour
    "trigger": ("invalid: cut-in never happens", "#d3d2cd", INK),
    "implausible": ("invalid: implausible motion", "#a3a29c", INK),
    "contact": ("invalid: ego already alongside", "#7b7a75", "white"),
    "no_interaction": ("no reaction needed", "#f3f2ee", INK),
    "low": ("useful, low criticality", "#b9d3f2", INK),
    "medium": ("useful, medium", "#6fa3e6", INK),
    "high": ("useful, high", "#2a5fae", "white"),
    "unavoidable": ("crash unavoidable", "#e34948", "white"),
}
ABBR = {"trigger": "T", "implausible": "P", "contact": "S", "no_interaction": "–",
        "low": "L", "medium": "M", "high": "H", "unavoidable": "U"}

plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 10, "axes.edgecolor": GRID,
                     "axes.labelcolor": MUTED, "xtick.color": MUTED, "ytick.color": MUTED})


def cls(r) -> str:
    if r.verdict == "invalid":
        if "implausible_motion" in str(r.issues):
            return "implausible"
        return "contact" if r.side_contact else "trigger"
    return "no_interaction" if r.verdict == "no_interaction" else r.criticality


def funnel(df: pd.DataFrame, out: Path) -> dict:
    valid = df[df.verdict != "invalid"]
    useful = df[df.verdict == "useful"]
    passable = useful[useful.criticality != "unavoidable"]
    distinct = passable.groupby(["dv_kmh", "gap_m", "t_lc_s"]).ngroups
    steps = [("Generated by the parameter sweep", len(df)),
             ("Valid: executable, plausible, cut-in happens", len(valid)),
             ("Relevant: the ego has to react", len(useful)),
             ("Passable: a car could still avoid the crash", len(passable)),
             ("Distinct: not a near-copy of another test", distinct)]
    fig, ax = plt.subplots(figsize=(8.2, 3.0))
    for i, (lab, n) in enumerate(steps):
        ax.barh(i, n, color="#2a78d6" if i == len(steps) - 1 else "#b9d3f2", height=0.62)
        ax.text(n + 2, i, f"{n}", va="center", color=INK, fontweight="bold")
        ax.text(-3, i, lab, va="center", ha="right", color=INK)
    ax.set_xlim(0, 160); ax.invert_yaxis(); ax.axis("off")
    fig.tight_layout(); fig.savefig(out / "fig1_funnel.png", dpi=200, bbox_inches="tight"); plt.close(fig)
    return dict(steps)


def grid_map(df: pd.DataFrame, out: Path) -> None:
    df = df.assign(cls=df.apply(cls, axis=1))
    # the verdicts are identical for every ego speed, so one block is enough
    per_speed = df.pivot_table(index=["dv_kmh", "gap_m", "t_lc_s"], columns="v_ego_kmh", values="cls", aggfunc="first")
    assert (per_speed.nunique(axis=1) == 1).all(), "verdicts differ between ego speeds"
    df = df[df.v_ego_kmh == 100]
    vs, dvs, gaps, ts = sorted(df.v_ego_kmh.unique()), sorted(df.dv_kmh.unique()), sorted(df.gap_m.unique()), sorted(df.t_lc_s.unique())
    fig, ax = plt.subplots(figsize=(9.2, 3.4))
    for r in df.itertuples():
        row = vs.index(r.v_ego_kmh) * len(dvs) + dvs.index(r.dv_kmh)
        col = ts.index(r.t_lc_s) * len(gaps) + gaps.index(r.gap_m)
        lab, fill, tc = CLASS_STYLE[r.cls]
        ax.add_patch(Rectangle((col + 0.04, row + 0.04), 0.92, 0.92, color=fill, lw=0))
        ax.text(col + 0.5, row + 0.52, ABBR[r.cls], ha="center", va="center", color=tc, fontsize=8)
    ncol, nrow = len(ts) * len(gaps), len(vs) * len(dvs)
    for k in range(1, len(ts)):
        ax.axvline(k * len(gaps), color="white", lw=4)
    for k in range(1, len(vs)):
        ax.axhline(k * len(dvs), color="white", lw=4)
    ax.set_xticks([c + 0.5 for c in range(ncol)], [f"{g:g}" for _ in ts for g in gaps], fontsize=8)
    ax.set_yticks([r + 0.5 for r in range(nrow)], [f"{d:+g}" for _ in vs for d in dvs], fontsize=8)
    for k, t in enumerate(ts):
        ax.text(k * len(gaps) + len(gaps) / 2, -0.9, f"lane change in {t:g} s", ha="center", color=INK)
    ax.set_xlabel("trigger gap (m)"); ax.set_ylabel("target − ego\nspeed (km/h)")
    ax.set_xlim(0, ncol); ax.set_ylim(nrow, -1.6); ax.tick_params(length=0)
    for s in ax.spines.values():
        s.set_visible(False)
    handles = [Rectangle((0, 0), 1, 1, color=CLASS_STYLE[k][1]) for k in CLASS_STYLE]
    labels = [f"{ABBR[k]}  {CLASS_STYLE[k][0]}" for k in CLASS_STYLE]
    ax.legend(handles, labels, loc="upper center", bbox_to_anchor=(0.5, -0.25), ncol=4, frameon=False, fontsize=8.5)
    fig.tight_layout(); fig.savefig(out / "fig2_grid.png", dpi=200, bbox_inches="tight"); plt.close(fig)


EXAMPLES = [
    ("cutin_v100_dv-20_g20_t2", "Useful, low criticality"),
    ("cutin_v100_dv+0_g60_t2", "No reaction needed"),
    ("cutin_v100_dv-40_g10_t2", "Unavoidable"),
    ("cutin_v100_dv-40_g35_t1", "Physically implausible (1 s lane change)"),
]


def examples(logs: Path, df: pd.DataFrame, out: Path) -> None:
    fig, axes = plt.subplots(2, 2, figsize=(9.2, 4.8), sharex=True, sharey=True)
    for ax, (name, title) in zip(axes.flat, EXAMPLES):
        d = metrics.load_log(str(logs / f"{name}.csv"))
        e, g = d["Ego"], d["Target"]
        r = df.set_index("name").loc[name]
        dx, y, t = (g.x - e.x).to_numpy(), g.y.to_numpy(), g.t.to_numpy()
        # show the approach until shortly after the target enters the ego path
        end = (r.t_entry + 0.5) if pd.notna(r.t_entry) else t[-1]
        keep = t <= end
        ax.axhspan(-6, 0, color="#f3f2ee"); ax.axhline(-3, color="white", lw=1.5, ls=(0, (6, 6)))
        ax.add_patch(Rectangle((-2.3, -1.5 - 0.95), 4.6, 1.9, color=INK))
        ax.text(0, -0.25, "ego", ha="center", va="bottom", fontsize=8, color=INK)
        ax.plot(dx[keep], y[keep], color="#2a78d6", lw=2)
        idx = np.arange(0, keep.sum(), 20)
        ax.scatter(dx[idx], y[idx], s=12, color="#2a78d6", zorder=3)
        ax.scatter([dx[0]], [y[0]], s=40, facecolor="white", edgecolor="#2a78d6", lw=1.5, zorder=4)
        k = keep.sum() - 1
        ax.annotate("", xy=(dx[k], y[k]), xytext=(dx[max(k - 6, 0)], y[max(k - 6, 0)]),
                    arrowprops=dict(arrowstyle="-|>", color="#2a78d6", lw=2))
        if r.verdict == "invalid":
            sub = f"target's sideways acceleration {r.max_target_lat_acc:.0f} m/s² (everyday: below ~3)"
        elif not np.isfinite(r.a_req):
            sub = "target cuts in so close that contact happens before braking"
        elif r.a_req < 0.05:
            sub = "target is as fast as the ego; no braking needed"
        else:
            sub = f"ego would need to brake at {r.a_req:.1f} m/s²"
        ax.set_title(f"{title}\n{sub}", fontsize=9.5, color=INK, loc="left")
        ax.set_xlim(-10, 60); ax.set_ylim(-6.5, 0.8)
        ax.set_yticks([-1.5, -4.5], ["ego lane", "neighbour\nlane"], fontsize=8); ax.tick_params(axis="y", length=0)
        ax.grid(False)
    for ax in axes[1]:
        ax.set_xlabel("distance ahead of the ego (m)   ·   ○ start, dots every 1 s")
    fig.tight_layout(); fig.savefig(out / "fig3_examples.png", dpi=200, bbox_inches="tight"); plt.close(fig)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=Path("outputs"))
    ap.add_argument("--docs", type=Path, default=Path("docs"))
    args = ap.parse_args()
    args.docs.mkdir(parents=True, exist_ok=True)
    df = pd.read_csv(args.out / "grid_results.csv")
    steps = funnel(df, args.docs)
    grid_map(df, args.docs)
    examples(args.out / "grid" / "logs", df, args.docs)
    (args.docs / "funnel.json").write_text(json.dumps(steps, indent=1))
    print(json.dumps(steps, indent=1))


if __name__ == "__main__":
    main()
